import { camelCase, kebabCase, pascalCase } from 'change-case';
import { XMLParser } from 'fast-xml-parser';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'fs';
import { EOL } from 'os';
import { join as pathJoin, parse as pathParse } from 'path';

export type ResxToTypeScriptOptions = {
    indentSize?: number;
    indentStyle?: 'space' | 'tab';
    resxFolder: string;
    resxEmpty?: 'export' | 'skip' | 'throw';
    typeScriptFolder: string;
    typeScriptNamespace?: string;
    typeScriptAccessModifier?: 'public' | 'protected';
    typeScriptPropertyType?: boolean;
};

export function resxToTypeScript(options: ResxToTypeScriptOptions): void {
    const resxFiles = recursiveSearchSync(options.resxFolder, /.resx$/);
    if (!resxFiles.length) return;

    mkdirSync(options.typeScriptFolder, { recursive: true });

    let parser = new XMLParser({
        ignoreAttributes: false,
        isArray: (_, jPath) => jPath === 'root.data',
    });
    let errors: { file: string; error: string }[] = [];
    for (let resxFile of resxFiles) {
        const resxName = pathParse(resxFile).name;
        const resxContent = readFileSync(resxFile);
        try {
            const resx = parser.parse(resxContent);
            const tsContent = buildTypeScript(resx, resxName, options);
            const tsFileName = pathJoin(options.typeScriptFolder, `${kebabCase(resxName)}.ts`);
            writeFileSync(tsFileName, tsContent);
        } catch (error) {
            if (error instanceof Error) {
                errors.push({ file: resxFile, error: error.message });
            } else {
                errors.push({ file: resxFile, error: `${error}` });
            }
        }
    }

    if (errors.length) throw new Error(errors.map(e => `${e.file}: ${e.error}`).join(EOL));
}

function buildTypeScript(
    resx: any,
    resxName: string,
    {
        indentStyle = 'space',
        indentSize = 2,
        typeScriptNamespace,
        typeScriptAccessModifier,
        typeScriptPropertyType,
        resxEmpty = 'skip',
    }: ResxToTypeScriptOptions,
): string {
    const rootNode = resx['root'];
    if (!rootNode) throw new Error('file is in an invalid format');

    const dataNodes = rootNode['data'] ?? [];
    if (!dataNodes.length) {
        if (resxEmpty === 'skip') return '';
        if (resxEmpty === 'throw') throw new Error('file is empty');
    }

    let content = `// Auto generated by resx-to-typescript (npm package)${EOL}${EOL}`;

    let indentCount = 0;
    const indent = (indentStyle === 'tab' ? '\t' : ' ').repeat(indentSize);
    const appendLine = (line: string) => (content += `${indent.repeat(indentCount)}${line}${EOL}`);

    if (typeScriptNamespace) {
        appendLine(`namespace ${typeScriptNamespace} {`);
        indentCount++;
    }

    const className = pascalCase(resxName);
    appendLine(`export class ${className} {`);
    indentCount++;

    for (let dataNode of dataNodes) {
        const name = dataNode['@_name'];
        const value = dataNode['value'].replaceAll("'", "\\'").replaceAll('\r', '\\r').replaceAll('\n', '\\n');

        let property = '';
        if (typeScriptAccessModifier) property += `${typeScriptAccessModifier} `;
        property += camelCase(name);
        if (typeScriptPropertyType) property += `: ${typeScriptPropertyType}`;
        property += ` = '${value}';`;
        appendLine(property);
    }

    indentCount--;
    appendLine(`}`);

    if (typeScriptNamespace) {
        indentCount--;
        appendLine(`}`);
    }

    return content;
}

function recursiveSearchSync(dir: string, filter: RegExp): string[] {
    return readdirSync(dir, { recursive: true })
        .map(e => pathJoin(dir, e as string))
        .filter(e => !statSync(e).isDirectory())
        .filter(f => filter.test(f)) as string[];
}
