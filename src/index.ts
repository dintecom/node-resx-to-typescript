import { kebabCase, pascalCase } from 'change-case';
import { XMLParser } from 'fast-xml-parser';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'fs';
import { EOL } from 'os';
import { join as pathJoin, parse as pathParse } from 'path';

export type ResxOptions = {
    indentSize?: number;
    indentStyle?: 'space' | 'tab';
    resxFolder: string;
    resxEmpty?: 'export' | 'skip' | 'throw';
};

export type ResxToTypeScriptOptions = ResxOptions & {
    /** Required, unless the deprecated `typeScriptFolder` is set. */
    outputFolder?: string;
    /** @deprecated Use `outputFolder` instead. */
    typeScriptFolder?: string;
    typeScriptNamespace?: string;
    typeScriptAccessModifier?: 'public' | 'protected';
    typeScriptPropertyType?: boolean;
};

export type ResxToJsonOptions = ResxOptions & {
    outputFolder: string;
};

type Resources = Record<string, string>;

export function resxToTypeScript(options: ResxToTypeScriptOptions): void {
    const outputFolder = options.outputFolder ?? options.typeScriptFolder;
    if (!outputFolder) throw new Error('outputFolder is required');

    const { typeScriptNamespace, typeScriptAccessModifier, typeScriptPropertyType } = options;

    resxConvert(options, outputFolder, '.ts', (resxName, resources, indent) => {
        let content = `// Auto generated by resx-to-typescript (npm package)${EOL}${EOL}`;

        let indentCount = 0;
        const appendLine = (line: string) => (content += `${indent.repeat(indentCount)}${line}${EOL}`);

        if (typeScriptNamespace) {
            appendLine(`namespace ${typeScriptNamespace} {`);
            indentCount++;
        }

        appendLine(`export class ${pascalCase(resxName)} {`);
        indentCount++;

        for (const [name, value] of Object.entries(resources)) {
            let property = '';
            if (typeScriptAccessModifier) property += `${typeScriptAccessModifier} `;
            property += name;
            if (typeScriptPropertyType) property += ': string';
            property += ` = '${escapeString(value)}';`;
            appendLine(property);
        }

        indentCount--;
        appendLine('}');

        if (typeScriptNamespace) {
            indentCount--;
            appendLine('}');
        }

        return content;
    });
}

export function resxToJson(options: ResxToJsonOptions): void {
    if (!options.outputFolder) throw new Error('outputFolder is required');

    resxConvert(options, options.outputFolder, '.json', (_, resources, indent) => {
        return `${JSON.stringify(resources, null, indent)}\n`;
    });
}

function resxConvert(
    options: ResxOptions,
    outputFolder: string,
    fileExtension: string,
    convert: (resxName: string, resources: Resources, indent: string) => string,
): void {
    const { resxFolder, resxEmpty = 'skip', indentStyle = 'space', indentSize = 2 } = options;

    const resxFiles = recursiveSearchSync(resxFolder, /\.resx$/i);
    if (!resxFiles.length) return;

    mkdirSync(outputFolder, { recursive: true });

    const indent = indentStyle === 'tab' ? '\t' : ' '.repeat(indentSize);
    const parser = new XMLParser({
        ignoreAttributes: false,
        // Resources are strings as they are: no numbers, no trimmed spaces.
        parseTagValue: false,
        trimValues: false,
        isArray: (_, jPath) => jPath === 'root.data',
    });

    const errors: string[] = [];
    for (const resxFile of resxFiles) {
        const resxName = pathParse(resxFile).name;
        try {
            const resources = readResources(parser.parse(readFileSync(resxFile)));
            if (!Object.keys(resources).length) {
                if (resxEmpty === 'skip') continue;
                if (resxEmpty === 'throw') throw new Error('file is empty');
            }

            const outputFile = pathJoin(outputFolder, `${kebabCase(resxName)}${fileExtension}`);
            writeFileSync(outputFile, convert(resxName, resources, indent));
        } catch (error) {
            errors.push(`${resxFile}: ${error instanceof Error ? error.message : error}`);
        }
    }

    if (errors.length) throw new Error(errors.join(EOL));
}

function readResources(resx: any): Resources {
    if (!resx || !('root' in resx)) throw new Error('file is in an invalid format');

    // An empty <root> is parsed as a string.
    const dataNodes: any[] = resx.root?.['data'] ?? [];
    return Object.fromEntries(
        dataNodes.map(dataNode => [lowerCaseFirstLetter(dataNode['@_name'].trim()), dataNode['value'] ?? '']),
    );
}

function escapeString(value: string): string {
    return value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\r', '\\r').replaceAll('\n', '\\n');
}

function recursiveSearchSync(dir: string, filter: RegExp): string[] {
    return readdirSync(dir, { recursive: true })
        .map(e => pathJoin(dir, e as string))
        .filter(e => !statSync(e).isDirectory())
        .filter(f => filter.test(f)) as string[];
}

function lowerCaseFirstLetter(text: string) {
    return text ? text.charAt(0).toLowerCase() + text.slice(1) : text;
}
